export function PixelText({ text }: { text: string }) {
  return <span role="img" aria-label={text} style={{ display: "inline", lineHeight: 1.65 }}>
    {text.toUpperCase().split(/\s+/).map((word, wordIndex) => <span key={wordIndex} aria-hidden="true">
      {wordIndex > 0 ? " " : null}
      <svg viewBox={`0 0 ${word.length * 6 - 1} 7`} aria-hidden="true" focusable="false" shapeRendering="crispEdges"
        style={{ display: "inline-block", width: `${(word.length * 6 - 1) / 7}em`, height: "1em", maxWidth: "100%", verticalAlign: "baseline" }}>
        {Array.from(word).flatMap((letter, index) => (glyphs[letter] ?? glyphs["?"]).split("/").flatMap((row, y) =>
          Array.from(row).map((pixel, x) => pixel === "1" ? <rect key={`${index}-${y}-${x}`} x={index * 6 + x} y={y} width="1" height="1" fill="currentColor" /> : null)))}
      </svg>
    </span>)}
  </span>;
}
